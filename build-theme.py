#!/usr/bin/env python3
"""Build standalone Nebula themes and an offline preview from the same CSS.

Usage:
    python3 build-theme.py                 # build CSS and preview
    python3 build-theme.py --themes-only   # build CSS before preview is ready
    python3 build-theme.py --check         # verify source and generated files

Only the Python standard library is required. This script reads and writes
inside this theme package; it never contacts or modifies a Gitea server.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import mimetypes
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
UPSTREAM = SRC / "upstream"
MANIFEST = ROOT / "metadata" / "source-manifest.json"
UPSTREAM_COMMIT = "829b49c1ae96015e345f9d2a0eb1ea7acd5f31e1"
DISPLAY_NAMES = {"light": "Nebula · 日间", "dark": "Nebula · 夜间", "auto": "Nebula · 自动"}
META_RE = re.compile(r"gitea-theme-meta-info\s*\{[^}]*\}\s*")
COMMENT_RE = re.compile(r"/\*.*?\*/", re.S)
URL_RE = re.compile(r"url\(\s*(?P<quote>['\"]?)(?P<url>.*?)(?P=quote)\s*\)", re.S)


def read(path: Path) -> str:
    if not path.is_file():
        raise ValueError(f"Required source is missing: {path.relative_to(ROOT)}")
    return path.read_text(encoding="utf-8")


def strip_meta(css: str) -> str:
    return META_RE.sub("", css).strip() + "\n"


def git_blob_sha(data: bytes) -> str:
    return hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()


def verify_upstream() -> dict:
    manifest = json.loads(read(MANIFEST))
    if manifest.get("commit") != UPSTREAM_COMMIT:
        raise ValueError("Unexpected upstream Gitea commit in source manifest")
    for item in manifest["source_files"]:
        path = ROOT / item["local"]
        data = path.read_bytes()
        if git_blob_sha(data) != item["git_blob_sha"]:
            raise ValueError(f"Upstream Git blob checksum mismatch: {item['local']}")
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise ValueError(f"Upstream SHA256 mismatch: {item['local']}")
    return manifest


def metadata(mode: str) -> str:
    return (
        "gitea-theme-meta-info {\n"
        f'  --theme-display-name: "{DISPLAY_NAMES[mode]}";\n'
        f'  --theme-color-scheme: "{mode}";\n'
        "}\n"
    )


def header(mode: str) -> str:
    return (
        f"/*! {DISPLAY_NAMES[mode]} — Nebula 2.1.2 for Gitea 28.2.0.\n"
        " * Self-contained official variable baseline + Nebula palette + shared UI.\n"
        f" * Upstream commit: {UPSTREAM_COMMIT}.\n"
        " * Upstream CSS: Copyright The Gitea Authors, MIT License.\n"
        " * Exact upstream license: src/upstream/GITEA-LICENSE.\n"
        " * Local font licenses are distributed with the font files.\n"
        " * Generated by build-theme.py; edit src files, then rebuild.\n"
        " */\n"
    )


def tokens(css: str) -> set[str]:
    return set(re.findall(r"(--[\w-]+)\s*:", COMMENT_RE.sub("", css)))


def validate_stylesheet(css: str, mode: str, baseline: str | None = None) -> None:
    """Check packaging invariants, without pretending to be a CSS renderer."""
    clean = COMMENT_RE.sub("", css)
    if re.search(r"@import\b", clean, re.I):
        raise ValueError(f"{mode}: external/base @import is not allowed in a standalone theme")
    if any(re.match(r"(?:https?:)?//", m.group("url"), re.I) for m in URL_RE.finditer(clean)):
        raise ValueError(f"{mode}: remote stylesheet/font/image URL found")
    blocks = META_RE.findall(clean)
    if len(blocks) != 1 or blocks[0].strip() != metadata(mode).strip():
        raise ValueError(f"{mode}: expected one complete, final metadata block")
    if not clean.rstrip().endswith(metadata(mode).strip()):
        raise ValueError(f"{mode}: metadata must be last for Gitea's backend parser")
    if baseline is not None:
        missing = tokens(baseline) - tokens(css)
        if missing:
            raise ValueError(f"{mode}: missing upstream variables: {', '.join(sorted(missing))}")
        dark_flags = re.findall(r"--is-dark-theme\s*:\s*([^;]+);", clean)
        expected = "true" if mode == "dark" else "false"
        if not dark_flags or dark_flags[-1].strip() != expected:
            raise ValueError(f"{mode}: --is-dark-theme does not match this theme")


def build_css() -> dict[str, str]:
    ui = (read(SRC / "nebula-ui.css") + "\n" + read(SRC / "nebula-geometry.css")
          + "\n" + read(SRC / "nebula-geometry-motion.css")
          + "\n" + read(SRC / "nebula-inner-pages.css"))
    fonts_path = SRC / "fonts.css"
    fonts = read(fonts_path).strip() + "\n\n" if fonts_path.is_file() else ""
    bodies: dict[str, str] = {}
    result: dict[str, str] = {}

    for mode in ("light", "dark"):
        baseline = read(UPSTREAM / f"theme-gitea-{mode}.css")
        palette = read(SRC / f"palette-{mode}.css")
        bodies[mode] = (
            f"/* Complete Gitea 28.2.0 {mode} theme baseline. */\n"
            + strip_meta(baseline)
            + "\n/* Nebula palette. */\n"
            + strip_meta(palette)
            + "\n/* Shared Nebula UI. */\n"
            + strip_meta(ui)
        )
        result[mode] = header(mode) + fonts + bodies[mode] + "\n" + metadata(mode)
        validate_stylesheet(result[mode], mode, baseline)

    # Font faces are common and occur once. Each media branch contains its
    # complete color baseline, palette and UI, including the dark emoji rules.
    result["auto"] = (
        header("auto")
        + fonts
        + "@media (prefers-color-scheme: light) {\n"
        + bodies["light"]
        + "}\n\n@media (prefers-color-scheme: dark) {\n"
        + bodies["dark"]
        + "}\n\n"
        + metadata("auto")
    )
    validate_stylesheet(result["auto"], "auto")
    return result


def local_asset(url: str) -> Path | None:
    """Map production assets/css relative font URLs to this package's fonts/."""
    if url.startswith(("data:", "#")):
        return None
    if re.match(r"(?:https?:)?//", url, re.I):
        raise ValueError(f"Remote asset is not allowed in the offline preview: {url}")
    raw = url.split("?", 1)[0].split("#", 1)[0]
    if raw.startswith("../fonts/"):
        path = ROOT / raw.removeprefix("../")
    elif raw.startswith("fonts/"):
        path = ROOT / raw
    else:
        # Themes are installed under assets/css; this is the equivalent path.
        path = ROOT / "css" / raw
    path = path.resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError(f"Asset escapes the theme package: {url}")
    if not path.is_file():
        raise ValueError(f"Missing local theme asset: {path.relative_to(ROOT)}")
    return path


def inline_assets(css: str) -> str:
    def replace(match: re.Match[str]) -> str:
        path = local_asset(match.group("url"))
        if path is None:
            return match.group(0)
        mime = {".woff2": "font/woff2", ".woff": "font/woff", ".ttf": "font/ttf"}.get(path.suffix.lower())
        mime = mime or mimetypes.guess_type(path.name)[0] or "application/octet-stream"
        content = base64.b64encode(path.read_bytes()).decode("ascii")
        return f'url("data:{mime};base64,{content}")'

    return URL_RE.sub(replace, css)


def js_string(text: str) -> str:
    # Safe even if a future CSS comment includes a closing script tag.
    return json.dumps(text, ensure_ascii=False).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def style_text(css: str) -> str:
    return re.sub(r"</style", r"<\\/style", css, flags=re.I)


def build_preview(themes: dict[str, str], manifest: dict) -> str:
    template = read(SRC / "preview-template.html")
    baseline = "\n\n".join(
        f"/* Gitea 28.2.0 source: {Path(item).name} */\n" + read(ROOT / item).rstrip()
        for item in manifest["preview_baseline_sources"]
    ) + "\n"
    embedded = {mode: inline_assets(css) for mode, css in themes.items()}
    js_path = SRC / "preview-interactions.js"
    interactions = read(js_path) if "__PREVIEW_INTERACTIONS_JS__" in template else ""
    values = {
        "__BASE_CSS__": style_text(baseline),
        "__LIGHT_CSS__": style_text(embedded["light"]),
        "__LIGHT_CSS_JSON__": js_string(embedded["light"]),
        "__THEME_CSS_JSON__": js_string(embedded["dark"]),
        "__AUTO_CSS_JSON__": js_string(embedded["auto"]),
        "__PREVIEW_INTERACTIONS_JS__": interactions,
    }
    # The interaction file may itself carry the JSON placeholders, so embed it
    # before replacing the CSS values, independent of dictionary iteration.
    template = template.replace("__PREVIEW_INTERACTIONS_JS__", interactions)
    for placeholder, value in values.items():
        template = template.replace(placeholder, value)
    remaining = sorted(set(re.findall(r"__[A-Z][A-Z0-9_]+__", template)))
    if remaining:
        raise ValueError(f"Unresolved preview placeholders: {', '.join(remaining)}")
    for attr in ("src",):
        if re.search(rf"\b{attr}\s*=\s*['\"](?:https?:)?//", template, re.I):
            raise ValueError("Offline preview contains an external resource src")
    return template


def write_or_check(path: Path, content: str, check: bool) -> None:
    data = content.encode("utf-8")
    if check:
        if not path.is_file() or path.read_bytes() != data:
            raise ValueError(f"Generated file is missing or stale: {path.relative_to(ROOT)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        # Atomic replacement keeps an interrupted build from leaving half a CSS.
        temporary = path.with_suffix(path.suffix + ".build-tmp")
        temporary.write_bytes(data)
        temporary.replace(path)
    print(f"{'Verified' if check else 'Built'} {path.relative_to(ROOT)} ({len(data):,} bytes)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--themes-only", action="store_true", help="skip the offline preview")
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    try:
        manifest = verify_upstream()
        themes = build_css()
        # Validate local font/image dependencies for production too. The result
        # is discarded here; only the preview receives embedded font data.
        for css in themes.values():
            for match in URL_RE.finditer(COMMENT_RE.sub("", css)):
                local_asset(match.group("url"))
        outputs = {ROOT / "css" / f"theme-nebula-{mode}.css": css for mode, css in themes.items()}
        if not args.themes_only:
            outputs[ROOT / "preview" / "nebula-preview.html"] = build_preview(themes, manifest)
        for path, content in outputs.items():
            write_or_check(path, content, args.check)
    except (OSError, ValueError, KeyError) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
